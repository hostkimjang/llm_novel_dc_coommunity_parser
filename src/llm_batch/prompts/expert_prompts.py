# OUTPUT ASSEMBLER - 최종 결과 조합
# =============================================================================

def assemble_final_output(
    post_id: int,
    gatekeeper_result: dict,
    decoder_result: dict,
    verifier_result: dict,
    critic_result: dict
) -> dict:
    """
    Combine all expert outputs into the final PickvelOutputItemV2 format.
    """
    verification = verifier_result.get("verification_result", {})
    analysis = critic_result.get("analysis", {})
    
    # Build identity
    identity = {
        "is_relevant": verification.get("is_relevant", False),
    }
    
    novel_id = verification.get("novel_identity")
    if novel_id and novel_id.get("official_novel_title"):
        identity["novel_identity"] = {
            "official_novel_title": novel_id.get("official_novel_title"),
            "heretic_url": novel_id.get("heretic_url"),
            "confidence": novel_id.get("confidence", "None"),
        }
    
    # Evidence
    evidence_chain = verification.get("evidence_chain", [])
    if evidence_chain:
        identity["evidence"] = {
            "found_in_comment": any(e.get("source") == "comment" for e in evidence_chain),
            "source_text": evidence_chain[0].get("content") if evidence_chain else None,
        }
    
    # Slang insight
    slang = verification.get("slang_insight")
    if slang and slang.get("detected_term"):
        identity["slang_insight"] = {
            "detected_term": slang.get("detected_term"),
            "decoded_term": slang.get("decoded_term"),
        }
    
    # Inference
    inference = verification.get("inference")
    if inference:
        identity["inference"] = inference
    
    # Reason
    identity["reason"] = verification.get("reason") or gatekeeper_result.get("noise_reason") or "분석 완료"
    
    return {
        "post_id": post_id,
        "identity": identity,
        "analysis": analysis if identity.get("is_relevant") else None,
    }
